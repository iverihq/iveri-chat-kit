#!/usr/bin/env node

/**
 * Pulls the published `chat-kit` namespace into `src/i18n/default-catalogue.ts`, which is committed.
 *
 * **Why the kit carries its own words.** Iveri's apps pull `chat-kit` beside their own namespaces and hand
 * the kit their `t`. A customer's app, signed in through the Baasi platform with an app secret, has no
 * access to `iveri-localization-api`, so without a catalogue in the package it would have nothing to pass
 * and every button would read as its key. The bundled catalogue is what `ChatProvider` formats with when no
 * `translate` is given.
 *
 * It is the same flow as `iveri-infra/scripts/pull-translations.mjs`, run before a release rather than by
 * CI, which cannot reach the service: sign in as the demo owner, take the latest release of the namespace
 * in every active locale, and **drop what the service served from a fallback**, because English stored under
 * `ka` would be formatted with Georgian plural rules. The runtime falls back itself and knows which locale
 * it landed in. The file is TypeScript rather than JSON so every bundler, Metro included, reads it without
 * import attributes.
 *
 *     IDENTITY_API_URL=http://localhost:3100 node scripts/pull-catalogue.mjs
 *
 * Both URLs default to the ports `pull-translations.mjs` defaults to; pass the ones `iveri-local.sh` uses.
 */
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import * as prettier from 'prettier';

const NAMESPACE = 'chat-kit';
const target = resolve(import.meta.dirname, '..', 'src', 'i18n', 'default-catalogue.ts');

const identityUrl = process.env.IDENTITY_API_URL ?? 'http://localhost:3000';
const localizationUrl = process.env.LOCALIZATION_API_URL ?? 'http://localhost:3005';

const demo = {
    tenantSlug: process.env.DEMO_TENANT_SLUG ?? 'iveri-demo',
    email: process.env.DEMO_EMAIL ?? 'demo@iveri.local',
    password: process.env.DEMO_PASSWORD ?? 'DemoPassword-2026!',
};

const request = async (url, token) => {
    const response = await fetch(url, {
        headers: { accept: 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) },
    });
    const text = await response.text();
    if (!response.ok) throw new Error(`GET ${url} returned ${response.status}: ${text}`);

    return JSON.parse(text);
};

const login = async () => {
    const response = await fetch(`${identityUrl}/api/v1/auth/login`, {
        method: 'POST',
        headers: { accept: 'application/json', 'content-type': 'application/json' },
        body: JSON.stringify(demo),
    });
    const text = await response.text();
    if (!response.ok) throw new Error(`Login failed with ${response.status}: ${text}`);

    return JSON.parse(text).tokens.accessToken;
};

const main = async () => {
    const token = await login();
    const locales = (await request(`${localizationUrl}/api/v1/locales`, token)).filter(
        (locale) => locale.isActive !== false,
    );
    const sourceLocale = locales.find((locale) => locale.isSource)?.code ?? 'en';
    const messages = {};
    let version = 0;

    for (const locale of locales) {
        const bundle = await request(
            `${localizationUrl}/api/v1/namespaces/${NAMESPACE}/releases/latest/bundle?locale=${locale.code}`,
            token,
        );
        version = bundle.version;
        messages[locale.code] = Object.fromEntries(
            Object.entries(bundle.messages)
                .filter(([key]) => !bundle.fallbacks[key])
                .sort(([a], [b]) => a.localeCompare(b)),
        );
    }

    const source = [
        '// Generated by `scripts/pull-catalogue.mjs` from the published `chat-kit` namespace. Do not edit by',
        '// hand: change the words in `localization-backoffice-web` or `iveri-infra/scripts/i18n/chat-kit.mjs`,',
        '// publish, and pull again.',
        "import type { ChatCatalogue } from './catalogue.type.js';",
        '',
        `export const CHAT_KIT_DEFAULT_CATALOGUE: ChatCatalogue = ${JSON.stringify(
            { namespace: NAMESPACE, version, sourceLocale, messages },
            null,
            4,
        )};`,
        '',
    ].join('\n');
    const options = (await prettier.resolveConfig(target)) ?? {};
    await writeFile(target, await prettier.format(source, { ...options, filepath: target }));

    const counts = locales.map((locale) => `${locale.code} ${Object.keys(messages[locale.code]).length}`);
    console.log(`${NAMESPACE}@v${version}: ${counts.join(', ')}`);
};

main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
});
